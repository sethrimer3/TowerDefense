/** Transparent cells are omitted. Pixel keys are row-major on the 16×16 grid. */
export function tabIconPixels(name: TabIconName, variant?: TabIconVariant): ReadonlyMap<number, string> {
  const pixels = new Map<number, string>();
  (variant ? ART[name][variant] : SELECTED[name]).forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== '.') pixels.set(y * 16 + x, PALETTE[row[x]]);
    }
  });
  return pixels;
}

export function paintTabIcon(canvas: HTMLCanvasElement, name: TabIconName, variant?: TabIconVariant) {
  canvas.width = canvas.height = 48;
  const ctx = canvas.getContext('2d')!;
  ctx.imageSmoothingEnabled = false;
  for (const [pixel, color] of tabIconPixels(name, variant)) {
    ctx.fillStyle = color;
    ctx.fillRect(pixel % 16 * 3, Math.floor(pixel / 16) * 3, 3, 3);
  }
}

/** Separate from world-icon data attributes so visual settings never repaint it as a city tile. */
export const tabIconHtml = (name: TabIconName) =>
  `<canvas class="ui-sprite tab-icon" width="48" height="48" data-tab-icon="${name}" aria-hidden="true"></canvas>`;
