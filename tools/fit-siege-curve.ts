/** Fit monotone thresholds from actual native win/loss training brackets.
 * Validate them with separate seeds. The published curve remains anchored to native floor/ceiling.
 * node --experimental-transform-types --import ./tests/pin-random.ts tools/fit-siege-curve.ts */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
export const CURVE_FIT_INPUTS = ["docs/design/siege-calibration-training.json", "tools/fit-siege-curve.ts"];
export function curveFitHash() {
  const h = createHash("sha256");
  for (const file of CURVE_FIT_INPUTS) h.update(file + "\0").update(readFileSync(new URL("../" + file, import.meta.url)));
  return h.digest("hex");
}
export function fitCurve() {
  const report = JSON.parse(readFileSync(new URL("../docs/design/siege-calibration-training.json", import.meta.url), "utf8"));
  if (report.kind !== "native-crossover-search" || report.split !== "training" || !Array.isArray(report.targets))
    throw Error("Fit requires native training brackets");
  // The floor and ceiling castles' estimates as the training observed them,
  // so the fit never shifts when a building is tweaked afterwards.
  const DPS_MIN: number = report.floor,
    DPS_MAX: number = report.ceiling;
  if (!(DPS_MIN > 0 && DPS_MAX > DPS_MIN)) throw Error("Training report lacks its floor and ceiling");
  const points = [
    { mmr: 100, target: DPS_MIN, status: "anchor" },
    ...report.targets.map((p: any) => ({ ...p, target: p.status === "bracketed" ? p.target * 0.8 : p.target })),
    { mmr: 2720, target: DPS_MAX, status: "anchor" },
  ];
  const blocks: { start: number; end: number; sum: number; weight: number }[] = [];
  for (let i = 1; i < points.length - 1; i++) {
    blocks.push({ start: i, end: i, sum: Math.log(Math.max(DPS_MIN, points[i].target)), weight: 1 });
    while (blocks.length > 1) {
      const a = blocks.at(-2)!,
        b = blocks.at(-1)!;
      if (a.sum / a.weight < b.sum / b.weight) break;
      blocks.splice(-2, 2, { start: a.start, end: b.end, sum: a.sum + b.sum, weight: a.weight + b.weight });
    }
  }
  const values: number[] = new Array(points.length);
  values[0] = DPS_MIN;
  values[points.length - 1] = DPS_MAX;
  for (const b of blocks) for (let i = b.start; i <= b.end; i++) values[i] = Math.exp(b.sum / b.weight);
  // A capacity-limited rank cannot be assigned a budget above its legal witness.
  for (let i = points.length - 2; i > 0; i--)
    values[i] = Math.min(values[i], points[i].status === "no-losing-castle-found" ? points[i].target : DPS_MAX, values[i + 1] / 1.0001);
  let previous = DPS_MIN;
  return points.map((p: any, i: number) => {
    const value = i === 0 ? DPS_MIN : i === points.length - 1 ? DPS_MAX : Math.round(Math.max(previous * 1.0001, values[i]) * 1e6) / 1e6;
    previous = value;
    return [p.mmr, value] as const;
  });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const anchors = fitCurve();
  writeFileSync(
    "src/campaign/siege-budget-config.ts",
    "// Generated by tools/fit-siege-curve.ts; do not edit.\n// node --experimental-transform-types --import ./tests/pin-random.ts tools/fit-siege-curve.ts\nexport const CURVE_INPUT_HASH=" +
      JSON.stringify(curveFitHash()) +
      ";\nexport const CURVE_ANCHORS=" +
      JSON.stringify(anchors, null, 2) +
      " as const;\n",
  );
  console.log(JSON.stringify({ hash: curveFitHash(), anchors }, null, 2));
}
