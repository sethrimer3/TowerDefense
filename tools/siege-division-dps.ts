/** Generate engine-independent division anchors; no live powers in generation. */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CURVE_ANCHORS } from "../src/campaign/siege-budget-config.ts";
export const DIVISION_INPUTS = ["src/campaign/siege-budget-config.ts", "tools/siege-division-dps.ts"];
export function divisionInputHash() {
  const h = createHash("sha256");
  for (const p of DIVISION_INPUTS) h.update(p + "\0").update(readFileSync(new URL("../" + p, import.meta.url)));
  return h.digest("hex");
}
export function divisionTable() {
  const anchors = CURVE_ANCHORS.map(([mmr, value]) => [mmr, value]),
    DPS_MIN = anchors[0][1],
    DPS_MAX = anchors.at(-1)![1];
  return Array.from({ length: 35 }, (_, tier) => {
    const mmr = tier === 1 ? 100 : tier * 80;
    if (!tier) return DPS_MIN * 0.8;
    let i = 0;
    while (i < anchors.length - 2 && mmr > anchors[i + 1][0]) i++;
    const [a, x] = anchors[i],
      [b, y] = anchors[i + 1];
    return Math.round(x * Math.pow(y / x, Math.max(0, Math.min(1, (mmr - a) / (b - a)))) * 1e6) / 1e6;
  }).map((n, i) => (i === 34 ? DPS_MAX : n));
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const table = divisionTable();
  writeFileSync(
    "src/campaign/siege-division-dps.ts",
    "// Generated by tools/siege-division-dps.ts; do not edit.\n// node --experimental-transform-types --import ./tests/pin-random.ts tools/siege-division-dps.ts\nexport const DIVISION_INPUT_HASH=" +
      JSON.stringify(divisionInputHash()) +
      ";\nexport const DIVISION_DPS=" +
      JSON.stringify(table, null, 2) +
      " as const;\n",
  );
  console.log(JSON.stringify(table));
}
