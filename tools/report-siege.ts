/** Refresh the reviewer-facing rank table from the actual completed run. */
import { readFileSync, writeFileSync } from "node:fs";
import { DIVISION_DPS } from "../src/campaign/siege-division-dps.ts";
import { rankLabel } from "../src/campaign/siege-ranks.ts";
import { DPS_MIN, DPS_MAX } from "../src/campaign/siege-ceiling.ts";
const report = JSON.parse(readFileSync("docs/design/siege-calibration.json", "utf8"));
if (report.rows.some((r: any) => !["won", "lost"].includes(r.phase))) throw Error("Incomplete raids cannot be reported as losses");
const number = (n: number) => n.toLocaleString("en-US", { maximumFractionDigits: 2 });
const rows = DIVISION_DPS.map(
  (dps, i) =>
    "| " +
    rankLabel(i * 80) +
    " | " +
    (i === 0 ? "0–79 (unreachable)" : i === 1 ? "100–159" : i === 34 ? "2720–3000" : i * 80 + "–" + (i * 80 + 79)) +
    " | " +
    number(dps) +
    " |",
);
const rankRows = Array.from({ length: 7 }, (_, rank) => {
  const cases = report.rows.filter((r: any) => Math.floor(Math.floor(r.mmr / 80) / 5) === rank),
    wins = cases.filter((r: any) => r.phase === "won").length;
  return (
    "| " +
    rankLabel(rank * 400)
      .split(" ")
      .slice(0, -1)
      .join(" ") +
    " | " +
    wins +
    " / " +
    cases.length +
    " | " +
    ((100 * wins) / cases.length).toFixed(1) +
    "% |"
  );
});
const section =
  "<!-- native-calibration:start -->\n\nGenerated by `tools/report-siege.ts` from the checked-in native trial results.\n\nThe native floor is **" +
  number(DPS_MIN) +
  " estimated DPS**; the bounded-search ceiling is **" +
  number(DPS_MAX) +
  "**. The held-out test armies won **" +
  report.wins +
  " / " +
  report.raids +
  " raids (" +
  (100 * report.winRate).toFixed(1) +
  "%)**, using seeds " +
  report.seedStart +
  "–" +
  (report.seedStart + report.samples - 1) +
  ", with a " + report.raidSeconds + "-second limit and hidden staging homes. These are deterministic offline test-army outcomes, with no strike spells, rather than observed player probabilities. " + report.samples + " cases per reachable division provide an initial calibration of the curve; per-rank results remain uneven, samples are small, and matchups matter.\n\n| Rank | Wins / raids | Observed share |\n| --- | ---: | ---: |\n" +
  rankRows.join("\n") +
  "\n\n| Division | MMR band | Estimated defensive DPS |\n| --- | --- | ---: |\n" +
  rows.join("\n") +
  "\n\n<!-- native-calibration:end -->";
let doc = readFileSync("docs/design/SIEGE_MATCHMAKING.md", "utf8");
if (doc.includes("<!-- native-calibration:start -->")) doc = doc.replace(/<!-- native-calibration:start -->[\s\S]*?<!-- native-calibration:end -->/, section);
else doc += "\n\n" + section + "\n";
writeFileSync("docs/design/SIEGE_MATCHMAKING.md", doc);
console.log(report.wins + "/" + report.raids + " " + (report.winRate * 100).toFixed(1) + "%");
